// Generates responsive WebP versions of every site photo referenced from the code or catalogue,
// and writes src/app/data/imageVariants.ts so <ImageWithFallback> knows which sizes exist.
// Run after adding or changing photos in public/product-images:  node scripts/optimize-images.mjs
// Requires ImageMagick (`magick`).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const sourceDir = path.join(root, 'public', 'product-images');
const outputDir = path.join(root, 'public', 'img');
const WIDTHS = [480, 640, 960, 1600];
const QUALITY = '78';

const walk = (dir) => readdirSync(dir).flatMap((name) => {
  const full = path.join(dir, name);
  return statSync(full).isDirectory() ? walk(full) : [full];
});

const referenced = new Set();
for (const file of walk(path.join(root, 'src')).filter((f) => /\.(tsx?|json)$/.test(f))) {
  for (const match of readFileSync(file, 'utf8').matchAll(/\/product-images\/([\w.-]+\.(?:jpe?g|png))/gi)) referenced.add(match[1]);
}

mkdirSync(outputDir, { recursive: true });
const variants = {};
for (const file of [...referenced].sort()) {
  const source = path.join(sourceDir, file);
  if (!existsSync(source)) { console.warn(`Missing source image: ${file}`); continue; }
  const base = file.replace(/\.[^.]+$/, '');
  const width = Number(execFileSync('magick', ['identify', '-format', '%w', `${source}[0]`]).toString());
  // Always make the smallest size; larger sizes only when the original is at least that wide.
  const sizes = WIDTHS.filter((w, i) => i === 0 || w <= width);
  for (const size of sizes) {
    const target = path.join(outputDir, `${base}-${size}.webp`);
    if (existsSync(target) && statSync(target).mtimeMs >= statSync(source).mtimeMs) continue;
    execFileSync('magick', [source, '-strip', '-auto-orient', '-resize', `${size}x>`, '-quality', QUALITY, '-define', 'webp:method=6', target]);
  }
  variants[file] = { width, sizes };
}

writeFileSync(path.join(root, 'src', 'app', 'data', 'imageVariants.ts'),
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand.\n// Maps a file in /product-images to its original width and the sizes available as /img/<name>-<size>.webp.\nexport const IMAGE_VARIANTS: Record<string, { width: number; sizes: number[] }> = ${JSON.stringify(variants, null, 2)};\n`);
console.log(`Optimised ${Object.keys(variants).length} images into public/img.`);
